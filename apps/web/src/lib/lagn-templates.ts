type People = MasterTemplate["sample"];

type LagnSeed = {
  id: string;
  category: EventCategory;
  nameMr: string;
  nameHi: string;
  nameEn: string;
  descMr: string;
  descHi: string;
  descEn: string;
  badge?: MasterTemplate["badge"];
  bgGradient: string;
  accentColor: string;
  blessing: string;
  title: string;
  price?: number;
  photoUrl: string;
  blank: People;
  sample: People;
};

const BLANK = (title: string, photoUrl?: string): People => ({
  personA: "[पहिल्या व्यक्तीचे नाव]",
  personB: "[दुसऱ्या व्यक्तीचे नाव]",
  surnames: "[आडनावे]",
  date: "YYYY-MM-DD",
  time: "[शुभमुहूर्त]",
  venue: "[स्थळ / मंगल कार्यालय]",
  city: "[शहर]",
  host: "[निमंत्रक परिवार]",
  parentsA: "[पालक तपशील]",
  parentsB: "[पालक तपशील]",
  tagline: title,
  qrLocation: "[पत्ता / लोकेशन]",
  photoUrl,
});

function lagn(seed: LagnSeed): MasterTemplate {
  return {
    id: seed.id,
    category: seed.category,
    nameMr: seed.nameMr,
    nameHi: seed.nameHi,
    nameEn: seed.nameEn,
    descMr: seed.descMr,
    descHi: seed.descHi,
    descEn: seed.descEn,
    badge: seed.badge ?? "NEW",
    bgGradient: seed.bgGradient,
    accentColor: seed.accentColor,
    cardStyle: "lagn-panel",
    defaultBlessing: seed.blessing,
    defaultTitle: seed.title,
    price: seed.price ?? 199,
    placeholders: {
      ...seed.blank,
      photoUrl: seed.photoUrl,
    },
    sample: {
      ...seed.sample,
      photoUrl: seed.photoUrl,
    },
  };
}

